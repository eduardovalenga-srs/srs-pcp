-- =============================================================
-- 068) Grupos de produto e capacidade produtiva por fábrica/processo
-- =============================================================

-- A localização dos processos passa a ser padronizada para as duas fábricas.
-- Os processos conhecidos recebem a atribuição usada no fluxo fabril atual.
update public.processes
   set location = case
     when code in ('MP', 'LASER', 'DB_CH', 'SERRA', 'DB_TB', 'PUNC', 'METALEIRA', 'FICEP', 'KIT')
       then 'Fábrica 1'
     when code in ('PRE_MTG', 'SOLDA', 'ACAB', 'QUALITY', 'EXP')
       then 'Fábrica 2'
     when lower(trim(coalesce(location, ''))) in ('fábrica 1', 'fabrica 1', 'f1')
       then 'Fábrica 1'
     when lower(trim(coalesce(location, ''))) in ('fábrica 2', 'fabrica 2', 'f2')
       then 'Fábrica 2'
     else null
   end;

create table public.product_groups (
  id bigint generated by default as identity primary key,
  family_description text not null
    check (length(trim(family_description)) between 1 and 120),
  family_abbreviation text not null
    check (family_abbreviation ~ '^[A-Z0-9]{1,3}$'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index product_groups_family_abbreviation_unique
  on public.product_groups (family_abbreviation);

create or replace trigger product_groups_set_updated_at
  before update on public.product_groups
  for each row execute function public.set_updated_at();

create table public.product_group_process_capacities (
  id uuid primary key default gen_random_uuid(),
  product_group_id bigint not null
    references public.product_groups (id) on delete cascade,
  factory text not null check (factory in ('Fábrica 1', 'Fábrica 2')),
  process_id uuid not null references public.processes (id) on delete restrict,
  unit text not null check (unit in ('KG', 'M2', 'UNIDADES')),
  capacity numeric(14, 3) not null check (capacity >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint product_group_process_capacities_unique
    unique (product_group_id, factory, process_id, unit)
);

create index product_group_process_capacities_group_idx
  on public.product_group_process_capacities (product_group_id, factory);

create or replace trigger product_group_process_capacities_set_updated_at
  before update on public.product_group_process_capacities
  for each row execute function public.set_updated_at();

-- Mantém as capacidades na mesma fábrica caso o processo seja realocado.
create or replace function public.sync_product_group_capacity_factory()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
  if new.location is distinct from old.location
     and exists (
       select 1 from public.product_group_process_capacities c
        where c.process_id = new.id
     ) then
    if new.location is null or new.location not in ('Fábrica 1', 'Fábrica 2') then
      raise exception 'Associe o processo a uma fábrica antes de alterar seu cadastro.';
    end if;

    update public.product_group_process_capacities
       set factory = new.location
     where process_id = new.id
       and factory is distinct from new.location;
  end if;
  return new;
end;
$$;

create trigger processes_sync_product_group_capacity_factory
  before update of location on public.processes
  for each row execute function public.sync_product_group_capacity_factory();

alter table public.product_groups enable row level security;
alter table public.product_group_process_capacities enable row level security;


-- Salva o grupo e todas as capacidades numa transação. O código do grupo é
-- derivado do id autoincremental e da abreviação: <id>-<abreviação>.
create or replace function public.save_product_group(
  p_group_id bigint,
  p_family_description text,
  p_family_abbreviation text,
  p_capacities jsonb
)
returns table (id bigint, group_type text)
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_group_id bigint;
begin
  if not public.is_admin() then
    raise exception 'Você não tem permissão para gerenciar grupos de produto.';
  end if;

  if p_family_description is null
     or length(trim(p_family_description)) not between 1 and 120 then
    raise exception 'Informe a descrição da família (máximo de 120 caracteres).';
  end if;

  if p_family_abbreviation is null
     or p_family_abbreviation !~ '^[A-Z0-9]{1,3}$' then
    raise exception 'A abreviação deve ter de 1 a 3 letras ou números maiúsculos.';
  end if;

  if jsonb_typeof(coalesce(p_capacities, 'null'::jsonb)) <> 'array' then
    raise exception 'Informe as capacidades dos processos.';
  end if;

  if exists (
    select 1 from public.processes p
     where p.location not in ('Fábrica 1', 'Fábrica 2') or p.location is null
  ) then
    raise exception 'Defina a fábrica de todos os processos antes de cadastrar o grupo.';
  end if;

  if exists (
    select 1
      from public.processes p
     where not exists (
       select 1
         from jsonb_to_recordset(p_capacities)
           as c(factory text, "processId" uuid, unit text, capacity numeric)
        where c."processId" = p.id and c.factory = p.location
     )
  ) then
    raise exception 'Informe ao menos uma capacidade para cada processo da fábrica correspondente.';
  end if;

  if exists (
    select 1
      from jsonb_to_recordset(p_capacities)
        as c(factory text, "processId" uuid, unit text, capacity numeric)
      join public.processes p on p.id = c."processId"
     where p.location is distinct from c.factory
  ) then
    raise exception 'O processo informado não pertence à fábrica selecionada.';
  end if;

  if p_group_id is null then
    insert into public.product_groups (family_description, family_abbreviation)
    values (trim(p_family_description), p_family_abbreviation)
    returning product_groups.id into v_group_id;
  else
    update public.product_groups
       set family_description = trim(p_family_description),
           family_abbreviation = p_family_abbreviation
     where product_groups.id = p_group_id
     returning product_groups.id into v_group_id;

    if v_group_id is null then
      raise exception 'Grupo de produto não encontrado.';
    end if;

    delete from public.product_group_process_capacities
     where product_group_id = v_group_id;
  end if;

  insert into public.product_group_process_capacities
    (product_group_id, factory, process_id, unit, capacity)
  select v_group_id, c.factory, c."processId", c.unit, c.capacity
    from jsonb_to_recordset(p_capacities)
      as c(factory text, "processId" uuid, unit text, capacity numeric);

  return query
    select v_group_id, v_group_id::text || '-' || p_family_abbreviation;
end;
$$;

revoke execute on function public.save_product_group(bigint, text, text, jsonb) from public, anon;
grant execute on function public.save_product_group(bigint, text, text, jsonb) to authenticated;
